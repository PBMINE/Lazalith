/// The glyph for `character`, or `None` if it has none.
///
/// A character outside the printable ASCII range has no glyph, and saying so lets
/// a caller decide what to do. The default is a filled box, which is what
/// [`glyph_or_box`] draws.
pub const fn glyph(character: char) -> Option<&'static [u8; GLYPH_WIDTH]> {
    let code = character as u32;
    if code < FIRST as u32 || code > LAST as u32 {
        return None;
    }
    let index = (code as u8 - FIRST) as usize;
    Some(&FONT[index])
}

/// The glyph for `character`, or a filled box if it has none.
///
/// A missing glyph is drawn as something visible on purpose: a word with a hole
/// in it is a message the reader cannot trust, and a box says "this character is
/// not in the font" without the frontend having to check.
const fn glyph_or_box(character: char) -> [u8; GLYPH_WIDTH] {
    match glyph(character) {
        Some(columns) => *columns,
        None => [0x7f, 0x41, 0x41, 0x41, 0x7f],
    }
}

/// How many pixels wide `text` is, including the spacing between glyphs.
///
/// The trailing spacing is not counted, so a string's width is the width of its
/// last glyph rather than one pixel more than it needs to be.
pub fn text_width(text: &str) -> usize {
    let characters = text.chars().count();
    if characters == 0 {
        return 0;
    }
    characters * (GLYPH_WIDTH + GLYPH_SPACING) - GLYPH_SPACING
}

/// The rows `text` needs, which is one glyph's height however long it is.
pub const fn text_height() -> usize {
    GLYPH_HEIGHT
}

/// Whether the pixel at `x` by `y` inside `text` is set.
///
/// This is the font's whole output in one function, and it is a function rather
/// than a draw call so that the frontend can compose text into whatever it is
/// drawing — a panel, a texture, a test's expected frame.
pub fn text_pixel(text: &str, x: usize, y: usize) -> bool {
    if y >= GLYPH_HEIGHT {
        return false;
    }
    let advance = GLYPH_WIDTH + GLYPH_SPACING;
    let index = x / advance;
    let within = x % advance;
    if within >= GLYPH_WIDTH {
        return false;
    }
    let Some(character) = text.chars().nth(index) else {
        return false;
    };
    let columns = glyph_or_box(character);
    columns[within] & (1 << y) != 0
}
