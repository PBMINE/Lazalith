//! A 5×7 bitmap font, because a debugger has to show words.
//!
//! # Why a font lives in the frontend
//!
//! A debugger's output is mostly text: register names, hex digits, an error
//! message. Drawing that with SDL means either a font API the frontend cannot
//! assume exists, or glyphs it carries itself. The second is what this is, and it
//! is the smaller dependency: 95 printable ASCII characters, five columns each,
//! seven rows tall.
//!
//! # The encoding
//!
//! Each glyph is five bytes. Each byte is one *column*, and its low seven bits are
//! the seven rows of that column, with bit zero at the top. That is the layout
//! almost every 5×7 LCD font uses, which is why these numbers are the numbers
//! they are rather than something invented here.
//!
//! Drawing a glyph is therefore: for each column, for each of its seven set bits,
//! set the pixel at (`x + column`, `y + row`). No scaling, no antialiasing, no
//! kerning — a debugger shows small text often, and crisp small text beats
//! smooth small text.
//!
//! # What is not here
//!
//! Nothing below `0x20` except nothing at all: control characters are not drawn,
//! and a character with no glyph draws as a filled box so that a missing glyph is
//! visible rather than invisible. A frontend that silently drew nothing for a
//! character it did not have would show a message with a hole in it and no way to
//! tell which word it was.

/// A glyph's width in pixels.
pub const GLYPH_WIDTH: usize = 5;

/// A glyph's height in pixels.
pub const GLYPH_HEIGHT: usize = 7;

/// The gap between glyphs, in pixels.
pub const GLYPH_SPACING: usize = 1;

/// The first character with a glyph.
const FIRST: u8 = 0x20;

/// The last character with a glyph.
const LAST: u8 = 0x7e;

/// The number of characters that have glyphs.
const GLYPHS: usize = (LAST - FIRST + 1) as usize;

